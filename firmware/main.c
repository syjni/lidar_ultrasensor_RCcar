/* P-control wall following (only used during normal straight driving).
 * Instead of bang-bang soft_left/soft_right (fixed correction), the inner wheel
 * is slowed proportionally to how far the right wall is from WALL_TARGET_CM, so
 * the car eases toward the target distance with less weaving.
 *   - No I term: LiDAR side values spike (519/659/UNKNOWN) and an integrator
 *     would wind up and shove the car off-line after a corner.
 *   - VALID range is set for the 40cm corridor: above WALL_VALID_MAX_CM there is no wall
 *     to follow (it is an opening), so we just drive straight and let the
 *     opening/corner logic handle it -- we do NOT chase a far "wall".
 *   - WALL_KP is sized for a moderate error range (target 20cm): a 6cm error gives
 *     6*KP correction, clamped to WALL_CORR_MAX so it never overpowers SPEED. */
#define WALL_KP             8      /* correction PWM per cm of distance error */
#define WALL_CORR_MAX       110    /* clamp on the proportional correction */
#define WALL_VALID_MIN_CM   8      /* below this the side reading is contact-range, not wall-follow */
#define WALL_VALID_MAX_CM   26     /* above this there is no right wall to follow (opening) */
#define FRONT_HIGH_CM       30     /* >= 30cm: HIGH speed (rare in a tight maze) */
#define FRONT_MID_CM        18     /* 18~29cm: MID speed */
#define FRONT_LOW_CM        10     /* 10~17cm: LOW speed, still keep moving */
#define FRONT_TOOCLOSE_CM   8      /* <= 8cm: avoid/turn/back up */
#define FRONT_EMERGENCY_CM  6      /* <= 6cm: immediate recovery */
#define SIDE_OPEN_CM        28      /* side >= this is a turnable opening (40cm maze) */
#define CORNER_FRONT_CM     10     /* start a corner escape before the nose is almost touching */

