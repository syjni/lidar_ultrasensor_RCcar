/* =========================
 * Backward / reverse gating (debounce + hysteresis)
 *
 * Reverse must NOT trigger on a single noisy LiDAR front sample. Backward is
 * allowed ONLY when one of the following is true, AND the rear is safe:
 *   (1) front has stayed <= FRONT_EMERGENCY_CM continuously for at least
 *       FRONT_EMERGENCY_HOLD_MS  (debounced emergency), OR
 *   (2) the car has been stuck for at least the stuck timeout (is_stuck()).
 * A single frame where front dips low does not reverse the car; it must persist.
 * ========================= */
#define FRONT_EMERGENCY_HOLD_MS 500   /* front must stay <= FRONT_EMERGENCY_CM this long before reverse */
#define FRONT_CLEAR_CM          11    /* hysteresis: front must rise above this to clear the emergency latch */

/* =========================
 * Dead-end detection + decision locking (anti-oscillation)
 *
 * A dead end is declared when the front is blocked AND neither side is open,
 * i.e. "front blocked && right blocked && left blocked", or equivalently
 * "front very close && both side distances are not open". Once a turn/recovery
 * maneuver is chosen, a decision lock prevents immediately flipping to the
 * opposite direction (no left-right-left wobble in corners).
 * ========================= */
#define DEADEND_FRONT_CM        8      /* front considered blocked for dead-end test */
#define DEADEND_NOT_OPEN_CM     26     /* side below this is not open (40cm maze) */
#define DECISION_COOLDOWN_MS    1000  /* after a turn/recovery, hold before any new side decision */

/* =========================
 * Front/side "blocked" vs "open" thresholds for the escape decision.
 *
 * These drive is_front_blocked() / is_left_blocked() / is_right_blocked() and
 * choose_escape_direction(). The escape policy is: when the front is blocked,
 * turn toward an OPEN side BEFORE ever considering backward. Backward is a last
 * resort reserved for a true dead end (front blocked AND both sides blocked).
 *
 * A side is "open" (turnable) when its distance is strictly greater than
 * SIDE_BLOCKED_CM. A side is "blocked" when its distance is <= SIDE_BLOCKED_CM,
 * OR when it is UNKNOWN (UNKNOWN is treated conservatively as blocked, so the car
 * never turns into a side it cannot see - but UNKNOWN alone never forces a
 * backup, because a real dead end needs BOTH sides blocked, not merely unseen).
 * ========================= */
#define FRONT_BLOCKED_CM        DEADEND_FRONT_CM   /* front <= this -> front is blocked */
#define SIDE_BLOCKED_CM         26     /* side <= this -> definitely a wall (40cm maze) */
#define SIDE_TURN_OPEN_CM       SIDE_OPEN_CM  /* side must be >= SIDE_OPEN_CM before we willingly turn into it */
#define CORNER_SIDE_WALL_CM     18      /* still used by contact_escape() default-direction logic */
/* SIDE_CORNER_DIFF_CM: was used by the old wider-side corner selection.
 * The pure right-hand rule no longer compares side widths. Kept only so any
 * stale reference still compiles; not used by the active decision path. */
#define SIDE_CORNER_DIFF_CM     3

/* SIDE_DANGER_CM / SIDE_ESCAPE_MS: were used by the old SIDE-AVOID dodging layer
 * (turn away just because a side was close). That layer was REMOVED because it
 * fought the right-hand rule. Physical wall safety is handled by contact_escape()
 * (<= CONTACT_CM) only. These remain defined but unused by the active path. */
#define SIDE_DANGER_CM          10
#define SIDE_ESCAPE_MS          260

/* Contact escape: if front/side is <= CONTACT_CM, the car is physically too
 * close to the wall to pivot cleanly. Make room first with a short rear-safe
 * backup, then turn away. This is the ONLY remaining side-proximity reflex. */
#define CONTACT_CM              6
#define CONTACT_BACKUP_MS       250

