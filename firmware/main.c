/*
 * COSE421 Term Project - Maze Runner RC Car (v9: narrow thresholds + monitored arc-reverse escape)
 *
 * Hardware layout for this build:
 * - LD19 LiDAR (front-mounted): front / right / left wall distances. SERCOM2, 230400 bps.
 * - Rear ultrasonic sensor: rear collision avoidance during backward / stuck recovery.
 *     Echo edges detected by EIC interrupt (EXTINT0 on PA16).
 * - LIS2DH12 accelerometer over I2C (SERCOM3, PA22/PA23). Speed sampled every 200ms,
 *     I2C read driven by SERCOM3 interrupt.
 * - SERCOM5 output can be routed either to PC UART debug or HC-06 Bluetooth.
 *   For demo Bluetooth logging, USE_BLUETOOTH_OUTPUT is set to 1 by default.
 *   In this build, SERCOM5 is routed to PA20/PA21 for external HC-06 wiring.
 * - Motor PWM generated by TCC0 (PA18 = left enable WO[2], PA19 = right enable WO[3]).
 *
 * Project requirement mapping (for the minimum-requirement code review):
 * - Ultrasonic echo transition is detected by INTERRUPT (EIC EXTINT0, both edges),
 *   not by polling. See EIC_setup() and EIC_Handler().
 * - Accelerometer I2C read is INTERRUPT driven (SERCOM3 I2C master ISR).
 *   See LIS2DH_start_accel_read_interrupt() and SERCOM3_Handler().
 * - Motor PWM is generated by a TIMER/COUNTER (TCC0, WO[2]/WO[3]). See TCC0_setup().
 * - Speed is measured every 200ms (ACCEL_PERIOD_MS) and streamed as CSV for graphing.
 * - turn_count is incremented ONLY inside real turn maneuvers; after 5 turns a
 *   "# FIVE_TURNS_DONE" marker is emitted exactly once so the log can be cut and
 *   the speed graph drawn.
 * - LiDAR interrupt is NOT required by the spec, so the LD19 is polled over SERCOM2
 *   UART and its packets are parsed in main (service_lidar_once()).
 *
 * Output routing:
 * - USE_BLUETOOTH_OUTPUT 0 -> SERCOM5 goes to the PC (Tera Term), 115200 bps, for
 *   UART debugging / bring-up.
 * - USE_BLUETOOTH_OUTPUT 1 -> SERCOM5 goes to an HC-06 Bluetooth module, 9600 bps.
 *   The same CSV stream (speed + distances) is sent over Bluetooth to the PC so the
 *   speed graph can be drawn after 5 turns.
 * - Only this one macro needs to change to switch between PC-UART debug and Bluetooth.
 *   The SERCOM5 pins are PA20 TX / PA21 RX in this build; only the baud
 *   rate and the cable/peer differ.
 *
 * >>> DEMO NOTE: when the HC-06 module is wired to SERCOM5 (PA20/PA21), build with
 *     USE_BLUETOOTH_OUTPUT = 1 so the CSV speed log is transmitted over Bluetooth. <<<
 */

