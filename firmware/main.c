void EIC_setup(void)
{
    /*
     * REQUIREMENT: ultrasonic echo transition detected by INTERRUPT.
     * EXTINT0 (PA16) senses BOTH edges (SENSE0 = 0x3): the rising edge starts the
     * echo timer and the falling edge stops it, all inside EIC_Handler(). No polling.
     */
    EIC->CONFIG[0].bit.FILTEN0 = 1;
    EIC->CONFIG[0].bit.SENSE0 = 0x3;    /* both edges -> rising and falling echo */
    EIC->INTENSET.bit.EXTINT0 = 1;
    EIC->CTRL.bit.ENABLE = 1;
    while (EIC->STATUS.bit.SYNCBUSY) ;
}

/*
 * RTC in COUNT32 mode as a free-running 8MHz counter.
 * Used purely as a microsecond time base for ultrasonic echo timing
 * (micros_rtc() = COUNT / 8). No compare interrupt is used here.
 */
void RTC_setup_10us(void)
{
    RTC->MODE0.CTRL.bit.ENABLE = 0;
    while (RTC->MODE0.STATUS.bit.SYNCBUSY) ;

    RTC->MODE0.CTRL.bit.SWRST = 1;
    while (RTC->MODE0.CTRL.bit.SWRST) ;

    RTC->MODE0.CTRL.bit.MODE = 0;        /* 32-bit counter */
    RTC->MODE0.CTRL.bit.PRESCALER = 0;   /* no prescale -> 8MHz tick */
    RTC->MODE0.CTRL.bit.MATCHCLR = 0;    /* free-running, do not clear on match */
    RTC->MODE0.COUNT.reg = 0;
    while (RTC->MODE0.STATUS.bit.SYNCBUSY) ;

    RTC->MODE0.CTRL.bit.ENABLE = 1;
    while (RTC->MODE0.STATUS.bit.SYNCBUSY) ;
}

void TCC0_setup(void)
{
    /*
     * REQUIREMENT: motor control PWM is generated by a TIMER/COUNTER (TCC0).
     * PA18 -> TCC0/WO[2] (left enable), PA19 -> TCC0/WO[3] (right enable).
     * NPWM mode: PER sets the period, CC[2]/CC[3] set independent left/right duty.
     * Use peripheral function F (0x05) for TCC0 on PA18/PA19.
     * This fixes the TC3 MPWM issue: TC3 CC[0] would be TOP, not an independent left duty.
     */
    PORT->Group[0].PINCFG[LEFT_PWM_PIN].reg = 0x41;
    PORT->Group[0].PMUX[9].bit.PMUXE = 0x05;

    PORT->Group[0].PINCFG[RIGHT_PWM_PIN].reg = 0x41;
    PORT->Group[0].PMUX[9].bit.PMUXO = 0x05;

    TCC0->CTRLA.bit.ENABLE = 0;
    while (TCC0->SYNCBUSY.bit.ENABLE) ;

    TCC0->CTRLA.bit.PRESCALER = 6;        /* /256 */
    TCC0->WAVE.bit.WAVEGEN = 2;           /* NPWM: CCx gives duty, PER gives period */
    while (TCC0->SYNCBUSY.bit.WAVE) ;

    TCC0->PER.reg = PWM_PERIOD;
    while (TCC0->SYNCBUSY.bit.PER) ;

    TCC0->CC[2].reg = 0;                  /* left duty */
    while (TCC0->SYNCBUSY.bit.CC2) ;
    TCC0->CC[3].reg = 0;                  /* right duty */
    while (TCC0->SYNCBUSY.bit.CC3) ;

    TCC0->CTRLA.bit.ENABLE = 1;
    while (TCC0->SYNCBUSY.bit.ENABLE) ;
}
